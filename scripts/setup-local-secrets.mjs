/**
 * Generate local secrets for the Cloudflare Pages Functions plane.
 *
 * WHY THIS EXISTS
 * ---------------
 * `shared/encryption.ts` is deliberately fail-closed: without
 * EIP_ENCRYPTION_MASTER_KEY (>= 32 UTF-8 bytes) `encrypt()` THROWS. That is the
 * correct production behaviour, but it means a developer running the Functions
 * plane locally cannot install a connector at all — the request dies with
 * "EIP_ENCRYPTION_MASTER_KEY is required" and there is no obvious cause.
 *
 * Wrangler reads local Pages Function secrets from `apps/web/.dev.vars`. This
 * script creates that file with a freshly generated 32-byte master key, plus the
 * identity service URL, so local development of the Functions plane behaves like
 * production instead of failing closed for the wrong reason.
 *
 * The file is gitignored. It NEVER contains production secrets, and the generated
 * key is for local development only — rotating it makes locally-stored connector
 * credentials undecryptable, which is correct and expected.
 *
 * Usage:  node scripts/setup-local-secrets.mjs [--force]
 */

import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'apps', 'web', '.dev.vars');
const force = process.argv.includes('--force');

/** Minimal .env parser (KEY=VALUE, optional quotes, ignores comments). */
function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

/** Pull the shared identity/Supabase values out of the repo-root .env if present. */
function readRootEnv() {
  const p = join(root, '.env');
  if (!existsSync(p)) return {};
  try {
    return parseEnv(readFileSync(p, 'utf8'));
  } catch {
    return {};
  }
}

const rootEnv = readRootEnv();

if (existsSync(target) && !force) {
  process.stdout.write(
    `apps/web/.dev.vars already exists — leaving it untouched.\n` +
    `Pass --force to regenerate (this makes existing local connector credentials unreadable).\n`,
  );
  process.exit(0);
}

const masterKey = randomBytes(32).toString('base64');
const port = process.env.IDENTITY_PORT || '3001';

const missing = [];
const lines = [
  '# Local Pages Functions secrets — generated by scripts/setup-local-secrets.mjs',
  '# Gitignored. Development only. Never commit real secrets here.',
  '',
  '# 32 random bytes (44 base64 chars). Rotating this makes locally-stored',
  '# connector credentials undecryptable — that is expected and safe.',
  `EIP_ENCRYPTION_MASTER_KEY="${masterKey}"`,
  '',
  `IDENTITY_API_URL="http://localhost:${port}"`,
  '',
];

if (rootEnv.SUPABASE_URL) lines.push(`SUPABASE_URL="${rootEnv.SUPABASE_URL}"`, '');
else missing.push('SUPABASE_URL');

if (rootEnv.SUPABASE_SERVICE_ROLE_KEY) lines.push(`SUPABASE_SERVICE_ROLE_KEY="${rootEnv.SUPABASE_SERVICE_ROLE_KEY}"`, '');
else missing.push('SUPABASE_SERVICE_ROLE_KEY');

if (rootEnv.JWT_SECRET) lines.push(`JWT_SECRET="${rootEnv.JWT_SECRET}"`, '');
else missing.push('JWT_SECRET');

if (rootEnv.PLATFORM_ADMIN_EMAILS) lines.push(`PLATFORM_ADMIN_EMAILS="${rootEnv.PLATFORM_ADMIN_EMAILS}"`, '');
else missing.push('PLATFORM_ADMIN_EMAILS (optional — only needed for Super Admin testing)');

writeFileSync(target, lines.join('\n'), 'utf8');

process.stdout.write(`Wrote apps/web/.dev.vars\n`);
process.stdout.write(`  EIP_ENCRYPTION_MASTER_KEY generated (${Buffer.byteLength(masterKey, 'utf8')} bytes)\n`);
process.stdout.write(`  IDENTITY_API_URL = http://localhost:${port}\n`);

if (missing.length) {
  process.stdout.write(`\nStill missing (copy them into apps/web/.dev.vars from your .env):\n`);
  for (const m of missing) process.stdout.write(`  - ${m}\n`);
} else {
  process.stdout.write(`  All required values carried over from the repo-root .env\n`);
}
