type ScheduledReport = {
  id: string; title: string; cadence: string; template?: string; enabled: boolean;
  lastRunAt: string | null; nextRunHint: string; createdAt: string;
  lastEmailStatus?: string;
  recipients?: string[];
  cc?: string[];
  bcc?: string[];
  sendHour?: number | null;
};

type MemoryNote = { id: string; title: string; body: string };

function asObj(raw: unknown): Record<string, unknown> {
  if (raw && typeof raw === 'object' && !Array.isArray(raw)) {
    return raw as Record<string, unknown>;
  }
  return {};
}

function normalize(raw: unknown): ScheduledReport[] {
  if (!Array.isArray(raw)) return [];
  return (raw as ScheduledReport[]).filter(
    (x) => x && typeof x === 'object' && typeof x.id === 'string',
  ).slice(0, 40);
}

function buildReportContent(params: {
  title: string;
  orgName: string;
  runAt: string;
  healthScore: number;
  openAlerts: number;
  openDecisions: number;
  connectedSystems: number;
  briefHighlight: string;
  timeline: { title: string; detail: string }[];
  memoryNotes: MemoryNote[];
  template?: string;
}, format: 'text' | 'html' = 'text'): string {
  if (format === 'html') {
    return buildHTMLReport(params);
  }
  
  const lines: string[] = [
    `${params.title}`,
    `Organization: ${params.orgName}`,
    `Generated: ${new Date(params.runAt).toLocaleString()}`,
    `${'─'.repeat(60)}`,
    '',
    `ENTERPRISE HEALTH SUMMARY`,
    `Health Score:        ${params.healthScore}/100`,
    `Connected Systems:   ${params.connectedSystems}`,
    `Open Alerts:         ${params.openAlerts}`,
    `Open Decisions:      ${params.openDecisions}`,
    '',
    `ELLINEA AI BRIEF`,
    params.briefHighlight || 'No brief available — sync a connector to generate insights.',
    '',
  ];

  if (params.timeline.length) {
    lines.push('RECENT TIMELINE');
    for (const ev of params.timeline.slice(0, 6)) {
      lines.push(`• ${ev.title}: ${ev.detail}`);
    }
    lines.push('');
  }

  if (params.memoryNotes.length) {
    lines.push('KEY MEMORY NOTES');
    for (const note of params.memoryNotes.slice(0, 5)) {
      lines.push(`• ${note.title}: ${note.body.slice(0, 200)}`);
    }
    lines.push('');
  }

  lines.push(`${'─'.repeat(60)}`);
  lines.push(`Generated by Ellines EIP · Ellinea AI`);
  lines.push(`Powered by Ellines Tech — Where Enterprise Systems Think Together`);

  return lines.join('\n');
}

