export const onRequest: PagesFunction<Env> = async (context) => {
  if (context.request.method === 'OPTIONS') return options();
  if (context.request.method !== 'POST') {
    return json({ statusCode: 405, message: 'Method not allowed' }, 405);
  }

  const auth = await requireAuth(context.env, context.request);
  if (auth instanceof Response) return auth;

  const adminErr = requireOrgAdmin(auth.role);
  if (adminErr) return adminErr;

  const reportId = context.params.id as string;
  const supabase = getAdminClient(context.env);

  const { data: existing, error: readErr } = await supabase
    .from('organizations')
    .select('settings, name')
    .eq('id', auth.organizationId)
    .maybeSingle();
  if (readErr) return json({ statusCode: 500, message: readErr.message }, 500);

  const settings = asObj(existing?.settings);
  const orgName = (existing as { name?: string })?.name || 'Your Organization';
  const reports = normalize(settings.workflowReports);
  const idx = reports.findIndex((r) => r.id === reportId);
  if (idx === -1) return json({ statusCode: 404, message: 'Report not found' }, 404);

  const report = reports[idx];
  const now = new Date().toISOString();

  // Check for format query param (text or html for PDF printing)
  const url = new URL(context.request.url);
  const format = url.searchParams.get('format') === 'html' ? 'html' : 'text';

  // Build report content from snapshot + memory
  const snapshot = asObj(settings.enterpriseSnapshot || {});
  const memoryRaw = settings.ellineaMemory;
  const memoryNotes: MemoryNote[] = Array.isArray(memoryRaw)
    ? (memoryRaw as MemoryNote[]).filter((n) => n && typeof n.id === 'string').slice(0, 10)
    : [];

  const reportBody = buildReportContent({
    title: report.title,
    orgName,
    runAt: now,
    healthScore: typeof snapshot.healthScore === 'number' ? snapshot.healthScore : 0,
    openAlerts: typeof snapshot.openAlerts === 'number' ? snapshot.openAlerts : 0,
    openDecisions: typeof snapshot.openDecisions === 'number' ? snapshot.openDecisions : 0,
    connectedSystems: typeof snapshot.connectedSystems === 'number' ? snapshot.connectedSystems : 0,
    briefHighlight: typeof snapshot.briefHighlight === 'string' ? snapshot.briefHighlight : '',
    timeline: Array.isArray(snapshot.timeline) ? (snapshot.timeline as { title: string; detail: string }[]).slice(0, 6) : [],
    memoryNotes,
    template: report.template,
  }, format);

  // Attempt multi-recipient email delivery (To / Cc / Bcc)
  const delivery = deliveryFromStored(report);
  const toList = delivery.recipients.length
    ? delivery.recipients
    : auth.email
      ? [auth.email]
      : [];
  let emailStatus = 'not_configured';
  const mailConfig = resolveMailConfig(context.env);
  if (!toList.length) {
    emailStatus = 'failed: no recipients';
  } else if (mailConfig) {
    const emailResult = await sendOutboundEmail(context.env, {
      to: toList,
      cc: delivery.cc,
      bcc: delivery.bcc,
      subject: `${report.title} — ${orgName} (${new Date(now).toLocaleDateString()})`,
      text: reportBody,
    }).catch((err) => ({
      ok: false,
      error: err instanceof Error ? err.message : 'Send failed',
      provider: 'none' as const,
      id: undefined,
    }));
    emailStatus = emailResult.ok
      ? `delivered_via_${emailResult.provider}`
      : `failed: ${emailResult.error}`;
  }

  const updated: ScheduledReport = {
    ...report,
    recipients: delivery.recipients,
    cc: delivery.cc,
    bcc: delivery.bcc,
    sendHour: delivery.sendHour,
    lastRunAt: now,
    lastEmailStatus: emailStatus,
    nextRunHint: nextRunHintFor(report.cadence, report.enabled, delivery.sendHour),
  };

  const next = reports.map((r, i) => (i === idx ? updated : r));
  
  // Save to report history
  const historyEntry = {
    id: `run_${Date.now()}_${Math.random().toString(36).slice(2, 9)}`,
    reportId: report.id,
    reportTitle: report.title,
    reportTemplate: report.template || 'custom',
    runAt: now,
    status: emailStatus.startsWith('delivered') ? 'sent' : emailStatus === 'not_configured' ? 'queued' : 'failed',
    emailStatus,
    recipientCount: toList.length + delivery.cc.length + delivery.bcc.length,
    reportBody,
    htmlBody: format === 'html' ? reportBody : undefined,
    reportChars: reportBody.length,
  };
  
  const existingHistory = Array.isArray(settings.reportHistory)
    ? (settings.reportHistory as typeof historyEntry[])
    : [];
  const newHistory = [historyEntry, ...existingHistory].slice(0, 200); // Keep last 200 runs
  
  const nextSettings = { ...settings, workflowReports: next, reportHistory: newHistory };

  const { error: writeErr } = await supabase
    .from('organizations')
    .update({ settings: nextSettings, updated_at: now })
    .eq('id', auth.organizationId);
  if (writeErr) return json({ statusCode: 500, message: writeErr.message }, 500);

  await supabase.from('audit_logs').insert({
    organization_id: auth.organizationId,
    user_id: auth.sub,
    action: 'workflow.report_run',
    resource: 'scheduled_report',
    metadata: {
      id: reportId,
      title: updated.title,
      emailStatus,
      toCount: toList.length,
      ccCount: delivery.cc.length,
      bccCount: delivery.bcc.length,
    },
  });

  return json({
    ...updated,
    emailStatus,
    reportChars: reportBody.length,
    deliveredTo: toList,
    deliveredCc: delivery.cc,
    deliveredBccCount: delivery.bcc.length,
  });
};
